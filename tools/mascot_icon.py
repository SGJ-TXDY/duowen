"""Generates the mascot launcher icon from the sprite in Mascot.kt (resting pose, light colours).

Usage:  python -I tools/mascot_icon.py
Writes  app/src/main/res/drawable/ic_launcher_mascot.xml       (adaptive foreground, full colour)
        app/src/main/res/drawable/ic_launcher_mascot_mono.xml  (themed-icon silhouette; eyes/mouth cut out)
Do not hand-edit the outputs: MascotLauncherIconTest checks them against MascotSprite.
"""
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main/java/cn/embeddedquiz"
RES = ROOT / "app/src/main/res/drawable"
VIEWPORT = 108
SAFE_RADIUS = 33  # adaptive icons keep a 66dp circle visible under every mask


def strings(block):
    return re.findall(r'"([^"]*)"', block)


def pairs(block):
    return [(int(a), int(b)) for a, b in re.findall(r"(\d+)\s+to\s+(\d+)", block)]


def sprite():
    kt = (SRC / "Mascot.kt").read_text(encoding="utf-8")
    body = strings(re.search(r"val BODY =\s*listOf\((.*?)\n\s*\)", kt, re.S).group(1))
    eyes = pairs(re.search(r"MascotEyes\.OPEN to listOf\(([^)]*)\)", kt).group(1))
    mouth = pairs(re.search(r"val MOUTH = listOf\(([^)]*)\)", kt).group(1))
    arm = re.search(r"val ARM_DOWN = (\d+) to listOf\(([^)]*)\)", kt)
    arm_row, arm_lines = int(arm.group(1)), strings(arm.group(2))
    foot = strings(re.search(r"val FOOT = listOf\(([^)]*)\)", kt).group(1))
    const = lambda name: int(re.search(rf"const val {name} = (\d+)", kt).group(1))
    width, offset, ground = const("BODY_WIDTH"), const("OFFSET_X"), const("GROUND")
    assert len(body) == 17, "BODY changed shape; recheck the pose maths below"

    # Same layering as MascotSprite.build(MascotPose()): body, eyes, mouth, arms, feet.
    top = ground - 18
    ink = {"#": "OUTLINE", "b": "BODY", "H": "HIGHLIGHT"}
    grid = {}

    def put(row, col, kind):
        if kind:
            grid[(col + offset, top + row)] = kind

    mirror = lambda col: width - 1 - col
    for r, line in enumerate(body):
        for c, ch in enumerate(line):
            put(r, c, ink.get(ch))
    for r, c in eyes:
        put(r, c, "EYE")
        put(r, mirror(c), "EYE")
    for r, c in mouth:
        put(r, c, "MOUTH")
    for i, line in enumerate(arm_lines):
        for j, ch in enumerate(line):
            put(arm_row + i, j - 3, ink.get(ch))
            put(arm_row + i, mirror(j - 3), ink.get(ch))
    for i, line in enumerate(foot):
        for j, ch in enumerate(line):
            put(17 + i, 4 + j, ink.get(ch))
            put(17 + i, mirror(4 + j), ink.get(ch))
    return grid


def colours():
    theme = (SRC / "Theme.kt").read_text(encoding="utf-8")
    light = re.search(r"else\s*MascotColors\(([^\n]*)\)", theme).group(1)
    values = re.findall(r"0xFF([0-9A-Fa-f]{6})", light)
    return dict(zip(["OUTLINE", "BODY", "HIGHLIGHT", "EYE", "MOUTH"], ["#FF" + v.upper() for v in values]))


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def layout(cells):
    xs = [x for x, _ in cells]
    ys = [y for _, y in cells]
    cx, cy = (min(xs) + max(xs) + 1) / 2, (min(ys) + max(ys) + 1) / 2
    # Largest cell (in 0.05 steps) that keeps every cell corner inside the safe circle.
    reach = max(math.hypot(x + dx - cx, y + dy - cy) for x, y in cells for dx in (0, 1) for dy in (0, 1))
    cell = math.floor(SAFE_RADIUS / reach * 20) / 20
    return cell, VIEWPORT / 2 - cx * cell, VIEWPORT / 2 - cy * cell


def path_data(cells, cell, ox, oy):
    rows = {}
    for x, y in cells:
        rows.setdefault(y, []).append(x)
    out = []
    for y in sorted(rows):
        xs = sorted(rows[y])
        start = prev = xs[0]
        for x in xs[1:] + [None]:
            if x is not None and x == prev + 1:
                prev = x
                continue
            w = (prev - start + 1) * cell
            out.append(f"M{fmt(ox + start * cell)},{fmt(oy + y * cell)}h{fmt(w)}v{fmt(cell)}h-{fmt(w)}z")
            if x is not None:
                start = prev = x
    return "".join(out)


def vector(paths, cell, ox, oy):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/mascot_icon.py from MascotSprite (resting pose); do not edit. cell={fmt(cell)} origin={fmt(ox)},{fmt(oy)} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{VIEWPORT}dp" android:height="{VIEWPORT}dp"',
        f'    android:viewportWidth="{VIEWPORT}" android:viewportHeight="{VIEWPORT}">',
    ]
    for colour, data in paths:
        lines.append(f'    <path android:fillColor="{colour}" android:pathData="{data}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    grid = sprite()
    cell, ox, oy = layout(grid)
    palette = colours()
    order = ["OUTLINE", "BODY", "HIGHLIGHT", "EYE", "MOUTH"]
    # The body colour first fills the whole silhouette, so anti-aliased edges between two inks never
    # show the background through; every other ink is painted over it.
    colour = [(palette["BODY"], path_data(list(grid), cell, ox, oy))] + [
        (palette[k], path_data([xy for xy, v in grid.items() if v == k], cell, ox, oy)) for k in order if k != "BODY"
    ]
    shape = [xy for xy, v in grid.items() if v not in ("EYE", "MOUTH")]
    mono = [("#FF000000", path_data(shape, cell, ox, oy))]
    for name, paths in [("ic_launcher_mascot.xml", colour), ("ic_launcher_mascot_mono.xml", mono)]:
        (RES / name).write_text(vector(paths, cell, ox, oy), encoding="utf-8", newline="\n")
        print(f"wrote {name} cell={fmt(cell)} origin={fmt(ox)},{fmt(oy)} cells={len(grid)}")


if __name__ == "__main__":
    sys.exit(main())
